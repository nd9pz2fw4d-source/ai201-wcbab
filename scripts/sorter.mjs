// Slide sorter: pick slides with check marks, then present only those.
import { chromium } from "playwright";
import path from "node:path";
const file = "file://" + path.resolve("dist/index.html");
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await p.goto(file + "?length=75#/1");
await p.waitForTimeout(600);
await p.keyboard.press("s");
await p.waitForTimeout(1500);
await p.screenshot({ path: "screenshots/interact/sorter.png" });
const count = async () => (await p.locator("header").innerText()).match(/(\d+) of 50 picked/)?.[1];
console.log("75 picked", await count());
await p.getByRole("button", { name: "Pick: One claim" }).click();
await p.getByRole("button", { name: "Pick: How ready are we?" }).click();
console.log("after toggles", await count());
await p.getByRole("button", { name: /Pick all of Open discussion/ }).click();
console.log("after act toggle", await count());
await p.waitForTimeout(800);
await p.screenshot({ path: "screenshots/interact/sorter-picked.png" });
await p.getByRole("button", { name: /Done · present/ }).click();
await p.waitForTimeout(400);
await p.keyboard.press("ArrowRight"); await p.waitForTimeout(300);
console.log("after title goes to", await p.evaluate(() => location.hash), "(want #/3, slide 2 unpicked)");
await p.reload(); await p.waitForTimeout(600);
await p.keyboard.press("m"); await p.waitForTimeout(500);
console.log("menu shows pick", await p.locator("text=Your pick: 33 slides").count());
await p.screenshot({ path: "screenshots/interact/sorter-menu.png" });
await p.getByRole("button", { name: /Reset to 75 min/ }).click();
console.log("back to standard", await p.locator("text=Pick slides").count());
// With no ?length in the URL and nothing saved, the deck opens with "My mix".
const fresh = await (await b.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
await fresh.goto(file + "#/1"); await fresh.waitForTimeout(600);
console.log("fresh opens My mix:", await fresh.locator("text=/^1 \\/ 38$/").count() === 1);
await fresh.keyboard.press("s"); await fresh.waitForTimeout(600);
console.log("sorter says My mix:", /38 of 50 picked · My mix/.test(await fresh.locator("header").innerText()));
await fresh.getByRole("button", { name: "Pick: How ready are we?" }).click();
await fresh.getByRole("button", { name: "Pick: How ready are we?" }).click();
await fresh.keyboard.press("Escape"); await fresh.reload(); await fresh.waitForTimeout(600);
await fresh.keyboard.press("m"); await fresh.waitForTimeout(400);
console.log("menu after reload shows My mix:", await fresh.locator("text=My mix: 38 slides").count() === 1);
await fresh.goto(file + "#/govern-questions"); await fresh.reload(); await fresh.waitForTimeout(3500);
await fresh.screenshot({ path: "screenshots/interact/govern-questions.png" });
console.log(errors.length ? errors : "no console errors");
await b.close();
